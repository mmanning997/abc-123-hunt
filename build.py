#!/usr/bin/env python3
"""Build the installable web app from the game source.

src/game.html is the same file that is published as the Claude artifact
(it has no <html>/<head> of its own). This wraps it in a full page with the
home-screen app tags and the bundled fonts, then writes a service worker whose
cache name is a hash of everything it serves, so an installed copy picks up
each new build.

Usage:  python3 build.py
"""
import hashlib
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src" / "game.html"
# The vault copy is where the game gets edited; pull it in when it's there.
VAULT = pathlib.Path.home() / "Obsidian" / "Obsidian Vault" / "Family" / "Kids Projects" / "ABC 123 Hunt - source.html"
ASSETS = [
    "manifest.webmanifest",
    "icons/icon-192.png",
    "icons/icon-512.png",
    "icons/apple-touch-icon.png",
    "fonts/andika-400.woff2",
    "fonts/andika-700.woff2",
    "fonts/grandstander.woff2",
]

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>ABC 123 Hunt</title>
<meta name="description" content="A letters, numbers and sight words game for kindergartners.">
<meta name="robots" content="noindex">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="ABC 123 Hunt">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="theme-color" content="#D6E3F2" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#1F2D29" media="(prefers-color-scheme: dark)">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" type="image/png" href="icons/icon-192.png">
<style>
/* The page reset the Claude artifact host normally supplies */
:root{color-scheme:light; box-sizing:border-box; padding-top:env(safe-area-inset-top,0px); padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0}
img{max-width:100%}
[hidden]{display:none!important}
/* Home-screen app touches: no text selection, callouts, rubber-band scroll or double-tap zoom under small fingers */
body{-webkit-user-select:none; user-select:none; -webkit-touch-callout:none; overscroll-behavior:none}
button{touch-action:manipulation}
/* Fonts ship with the app so it works offline */
@font-face{font-family:"Andika"; font-style:normal; font-weight:400; font-display:swap; src:url(fonts/andika-400.woff2) format("woff2")}
@font-face{font-family:"Andika"; font-style:normal; font-weight:700; font-display:swap; src:url(fonts/andika-700.woff2) format("woff2")}
@font-face{font-family:"Grandstander"; font-style:normal; font-weight:700 900; font-display:swap; src:url(fonts/grandstander.woff2) format("woff2")}
</style>
</head>
<body>
"""

FOOT = """<script>
if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => {}));
</script>
</body>
</html>
"""

SW = """// Generated by build.py. Offline support for the home-screen app.
const CACHE = "abc123hunt-__HASH__";
const ASSETS = __ASSETS__;
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  if (req.mode === "navigate") {
    // The page itself: network first so a new build shows up, saved copy when offline
    e.respondWith(fetch(req).then(res => {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put("index.html", copy));
      return res;
    }).catch(() => caches.match("index.html")));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req)));
});
"""


def main():
    if VAULT.exists() and (not SRC.exists() or VAULT.read_bytes() != SRC.read_bytes()):
        SRC.parent.mkdir(exist_ok=True)
        shutil.copyfile(VAULT, SRC)
        print(f"Pulled the game source from the vault: {VAULT}")
    game = SRC.read_text(encoding="utf-8")
    # The head above carries the title, and the fonts are local, so drop those lines from the artifact source
    game = re.sub(r"^<title>.*?</title>\n", "", game, count=1, flags=re.M)
    game = re.sub(r'^<link rel="(?:preconnect|stylesheet)" href="https://fonts\.[^\n]*\n', "", game, flags=re.M)
    if "fonts.googleapis.com" in game or "fonts.gstatic.com" in game:
        raise SystemExit("The game source still loads fonts from the web; update the strip rule in build.py.")
    (ROOT / "index.html").write_text(HEAD + game + FOOT, encoding="utf-8")

    digest = hashlib.sha256()
    for rel in ["index.html"] + ASSETS:
        digest.update((ROOT / rel).read_bytes())
    stamp = digest.hexdigest()[:12]
    assets = "[" + ", ".join(f'"{a}"' for a in ["./", "index.html"] + ASSETS) + "]"
    (ROOT / "sw.js").write_text(SW.replace("__HASH__", stamp).replace("__ASSETS__", assets), encoding="utf-8")
    print(f"Built index.html and sw.js (cache abc123hunt-{stamp})")


if __name__ == "__main__":
    main()
